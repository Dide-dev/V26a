    <h1 class="page__heading pb-2">Gebruik van de dienst door minderjarigen</h1>
    <p class="pb-1.5">
        Onze dienst is bedoeld voor gebruik binnen het onderwijs. Leerlingen kunnen onder andere via
        een docent of onderwijsinstelling toegang krijgen tot de dienst. Onze website is openbaar
        toegankelijk. Voor bepaalde functies, zoals deelname aan een klaslokaal, kunnen leerlingen
        gebruikmaken van een door een docent verstrekte klaslokaalcode.
    </p>
    <p class="pb-1.5">
        Bij deelname aan een klaslokaal wordt een leerling gevraagd een naam in te voeren. Wij
        verzoeken gebruikers geen onnodige persoonsgegevens te verstrekken. Omdat gebruikers zelf
        bepalen welke naam zij invoeren, kan het voorkomen dat persoonsgegevens van leerlingen
        worden verwerkt. De door leerlingen ingevoerde naam wordt uitsluitend gebruikt voor de
        werking van de klaslokaalfunctionaliteit en voor het tonen van deelnemers binnen het
        betreffende klaslokaal aan de docent.
    </p>
    <p class="pb-1.5">
        Voor zover persoonsgegevens van minderjarigen worden verwerkt, gebeurt dit uitsluitend voor
        het aanbieden en functioneren van de dienst binnen de onderwijscontext. Indien een ouder,
        verzorger, of onderwijsinstelling van mening is dat onjuist of onrechtmatig persoonsgegevens
        van een minderjarige zijn verwerkt, neem dan contact met ons op via <a
            href="mailto:fi@uu.nl">fi@uu.nl</a
        >. Wij zullen een dergelijk verzoek onderzoeken en, indien de verwerking onrechtmatig blijkt
        of de gegevens niet langer noodzakelijk zijn, passende maatregelen nemen, waaronder
        verwijdering van de betreffende gegevens.
    </p>
