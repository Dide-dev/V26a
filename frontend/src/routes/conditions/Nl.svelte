<div>
    <h1 class="page__title pb-1">Voorwaarden</h1>
    <p class="pb-2 italic *:*:inline">Laatst geupdatet: 9 juni 2026</p>

    <h1 class="page__heading">Artikel 1 - Definities</h1>
    <p class="pb-1.5">In deze voorwaarden wordt verstaan onder:</p>
    <p class="pb-1.5">
        <b>Dienst:</b> de door Freudenthal Instituut aangeboden website en bijbehorende functionaliteiten.
    </p>
    <p class="pb-1.5">
        <b>Gebruiker:</b> iedere natuurlijke persoon die gebruik maakt van de Dienst.
    </p>
    <p class="pb-1.5">
        <b>Auteur:</b> een Gebruiker die heuristiekbomen kan aanmaken, beheren, of publiceren.
    </p>
    <p class="pb-1.5">
        <b>Leerling:</b> een Gebruiker die deelneemt aan een Klaslokaal of gebruik maakt van gepubliceerde
        heuristiekbomen.
    </p>
    <p class="pb-1.5">
        <b>Klaslokaal:</b> een door een Auteur aangemaakte omgeving waarin bomen met Leerlingen kunnen
        worden gedeeld.
    </p>
    <p class="pb-1.5">
        <b>Heuristiekboom:</b> een door een Gebruiker aangemaakte boomstructuur bestaande uit één of meer
        hintkaarten die Leerlingen stapsgewijs ondersteunen bij het oplossen van een opdracht.
    </p>
    <p class="pb-1.5">
        <b>Boominhoud:</b> alle gegevens die onderdeel uitmaken van of gekoppeld zijn aan een Heuristiekboom,
        waaronder mede begrepen opdrachtteksten, afbeeldingen, beschrijvingen, boekgegevens, ISBN-nummers,
        auteursnamen, hoofdstukverwijzingen, opgavenummers, vakken, labels, titels, en overige data.
    </p>

    <h1 class="page__heading">Artikel 2 - Toepasselijkheid</h1>
    <p class="pb-1.5">
        Deze algemene voorwaarden zijn van toepassing op ieder gebruik van de Dienst.
    </p>
    <p class="pb-1.5">
        Door gebruik te maken van de Dienst aanvaardt de Gebruiker deze voorwaarden.
    </p>

    <h1 class="page__heading">Artikel 3 - Gebruik van de Dienst</h1>
    <p class="pb-1.5">
        De Gebruiker zal de Dienst uitsluitend gebruiken overeenkomstig deze voorwaarden en
        toepasselijke wet- en regelgeving
    </p>
    <p class="pb-1.5">Het is niet toegestaan:</p>
    <ul>
        <li>inbreuk te maken op intellectuele eigendomsrechten van derden;</li>
        <li>de Dienst te gebruiken voor onrechtmatige doeleinden;</li>
        <li>beveiligingen te omzeilen;</li>
        <li>de beschikbaarheid of de werking van de Dienst te verstoren;</li>
        <li>malware of andere schadelijke programmatuur te verspreiden.</li>
    </ul>

    <h1 class="page__heading">Artikel 4 - Accounts</h1>
    <p class="pb-1.5">Voor bepaalde onderdelen van de Dienst is een account vereist.</p>
    <p class="pb-1.5">
        De Gebruiker is verantwoordelijk voor alle activiteiten die plaatsvinden via diens account,
        voor zover deze het gevolg zijn van het onvoldoende beschermen van accountgegevens.
    </p>
    <p class="pb-1.5">
        Freudenthal Instituut mag accounts blokkeren of verwijderen indien sprake is van misbruik of
        overtreding van deze voorwaarden.
    </p>

    <h1 class="page__heading">Artikel 5 - Gebruikersinhoud en Heuristiekbomen</h1>
    <p class="pb-1.5">
        Het auteursrecht op door Gebruikers gecreëerde Heuristiekbomen blijft berusten bij de maker
        daarvan, tenzij uit de wet of een overeenkomst met een werkgever anders voortvloeit.
    </p>
    <p class="pb-1.5">
        Door Heuristiekbomen via de Dienst beschikbaar te stellen verleent de Gebruiker aan
        Freudenthal Instituut een niet-exclusieve, wereldwijde, en kosteloze licentie om dit
        materiaal op te slaan, te verwerken, weer te geven en beschikbaar te stellen voor zover
        noodzakelijk voor het functioneren van de Dients.
    </p>
    <p class="pb-1.5">
        Heuristiekbomen zijn standaard uitsluitend zichtbaar voor de maker, tenzij de maker ervoor
        kiest het materiaal openbaar te publiceren of beschikbaar te stellen binnen een Klaslokaal.
    </p>

    <h1 class="page__heading">Artikel 6 - Publicatie onder Creative Commons</h1>
    <p class="pb-1.5">
        Wanneer een Auteur Heuristiekbomen openbaar publiceert via de Dienst, wordt die
        Heuristiekboom en de Boominhoud beschikbaar gesteld onder de Creative Commons
        Attribution-ShareAlike 4.0 International (CC BY-SA 4.0) licentie.
    </p>
    <p class="pb-1.5">
        Door openbaar publiceren verklaart de Auteur bevoegd te zijn deze licentie op de betreffende
        Heuristiekboom en Boominhoud toe te passen.
    </p>
    <p class="pb-1.5">
        De volledige licentievoorwaarden zijn beschikbaar via <a
            href="https://creativecommons.org/licenses/by-sa/4.0/deed.en"
            >de website van Creative Commons</a
        >.
    </p>

    <h1 class="page__heading">Artikel 7 - Lesmateriaal van derden</h1>
    <p class="pb-1.5">
        Gebruikers mogen uitsluitend lesmateriaal uploaden of publiceren waarvoor zij over de
        benodigde rechten beschikken.
    </p>
    <p class="pb-1.5">
        Het is niet toegestaan zonder toestemming van de rechthebbende auteursrechtelijk beschermd
        materiaal van derden via de Dienst openbaar te maken, waaronder mede begrepen:
    </p>
    <ul>
        <li>opdrachten uit lesmethoden;</li>
        <li>examens;</li>
        <li>toetsmateriaal;</li>
        <li>afbeeldingen;</li>
        <li>teksten uit boeken.</li>
    </ul>
    <p class="pb-1.5">
        Gebruikers zijn zelf verantwoordelijk voor de rechtmatigheid van door hen geplaatste inhoud.
    </p>
    <p class="pb-1.5">
        De Gebruiker vrijwaart Freudenthal Instituut voor aanspraken van derden die voortvloeien uit
        door de Gebruiker geplaatste inhoud.
    </p>

    <h1 class="page__heading">Artikel 8 - Open source software</h1>
    <p class="pb-1.5">
        De broncode van de software waarop de Dienst is gebaseerd wordt beschikbaar gesteld onder de
        GNU Affero General Public License, versie 3 (AGPLv3).
    </p>
    <p class="pb-1.5">
        Deze licentie is uitsluitend van toepassing op de software en niet op door Gebruikers
        gecreëerde Heuristiekbomen.
    </p>

    <h1 class="page__heading">Artikel 9 - Beschikbaarheid van de Dienst</h1>
    <p class="pb-1.5">
        Freudenthal Instituut streeft naar een goede beschikbaarheid van de Dienst, maar geeft geen
        garantie dat de Dienst te allen tijde zonder onderbrekingen of fouten beschikbaar zal zijn.
    </p>
    <p class="pb-1.5">
        Freudenthal Instituut mag de Dienst tijdelijk buiten gebruik stellen voor onderhoud,
        beveiligingsmaatregelen of technische aanpassingen.
    </p>

    <h1 class="page__heading">Artikel 10 - Aansprakelijkheid</h1>
    <p class="pb-1.5">
        Freudenthal Instituut streeft naar een betrouwbare beschikbaarheid van de Dienst, maar
        garandeert niet dat de Dienst te allen tijde zonder onderbrekingen of storingen beschikbaar
        zal zijn.
    </p>
    <p class="pb-1.5">
        Freudenthal Instituut is uitsluitend aansprakelijk voor directe schade die het rechtstreekse
        gevolg is van opzet of bewuste roekeloosheid van Freudenthal Instituut.
    </p>
    <p class="pb-1.5">
        Voor zover wettelijk toegestaan is Freudenthal Instituut niet aansprakelijk voor indirecte
        schade, gevolgschade, gederfde inkomsten, verlies van gegevens, of schade voortvloeiend uit
        het gebruik van door derden geplaatste inhoud.
    </p>
    <p class="pb-1.5">
        Niets in deze voorwaarden beperkt aansprakelijkheid voor zover beperking op grond van
        toepasselijk recht niet is toegestaan.
    </p>

    <h1 class="page__heading">Artikel 11 - Privacy</h1>
    <p class="pb-1.5">Bij het gebruik van de Dienst kunnen persoonsgegevens worden verwerkt.</p>
    <p class="pb-1.5">
        De verwerking van persoonsgegevens vindt plaats overeenkomstig het <a href="\privacy"
            >privacybeleid</a
        >.
    </p>

    <h1 class="page__heading">Artikel 12 - Wijzigingen</h1>
    <p class="pb-1.5">Freudenthal Instituut kan deze voorwaarden wijzigen.</p>
    <p class="pb-1.5">Wijzigingen worden bekendgemaakt via de Dienst</p>
    <p class="pb-1.5">
        Voortgezet gebruik van de Dienst na inwerkingtreding van gewijzigde voorwaarden geldt als
        aanvaarding daarvan.
    </p>

    <h1 class="page__heading">Artikel 13 - Toepasselijk recht</h1>
    <p class="pb-1.5">
        Op deze voorwaarden en het gebruik van de Dienst is uitsluitend Nederlands recht van
        toepassing.
    </p>

    <h1 class="page__heading">Artikel 14 - Geschillen</h1>
    <p>
        Geschillen die voortvloeien uit of verband houden met deze voorwaarden worden voorgelegd aan
        de bevoegde rechter in Nederland.
    </p>
</div>
