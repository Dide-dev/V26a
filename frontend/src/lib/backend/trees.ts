import type { CardGetData, CardId } from './cards';
import { apiCallPost, apiCallGet, apiCallDelete } from './index';
import type { Option } from './types';
import type { UserId } from './users';

const prefix = 'trees/';

function apiCallPostTree(path: string, body: unknown) {
    return apiCallPost(prefix + path, body);
}

function apiCallGetTree(path: string) {
    return apiCallGet(prefix + path);
}

function apiCallDeleteTree(path: string) {
    return apiCallDelete(prefix + path);
}

export type TreeId = number;

/** All data of the tree, together with its cards. */
export type TreeWithCards = {
    data: TreeData;
    genData: TreeGeneratedData;
    structure: TreeStructure;
    cards: Record<CardId, CardGetData>;
};

/** The general data of the tree, NOT including its structure or autogenerated data. */
export type TreeData = {
    title: string;
    description: Option<string>;
    bookName: Option<string>;
    bookEdition: Option<string>;
    bookIsbn: Option<string>;
    bookChapter: Option<string>;
    bookExercise: Option<string>;
    assignmentText: Option<string>;
    published: boolean;
};

/** The tree structure with the cards. */
export type TreeStructure = {
    rootNodes: RootNode[];
};

/** A root node of a tree. */
export type RootNode = {
    label: string;
    children: Node[];
};

/** A node (not root) in a tree. */
export type Node = {
    cardId: CardId;
    children: Node[];
};

/** The autogenerated data of the tree. */
export type TreeGeneratedData = {
    id: TreeId;
    ownerId: UserId;
    createdAt: Date;
    lastModified: Date;
    timesVisited: number;
    lastVisited: Option<Date>;
};

export type TreeMetadata = {
    data: TreeData;
    genData: TreeGeneratedData;
};

export type TreeAddData = {
    treeData: TreeData;
    treeStructure: TreeStructure;
};

// Default tree structure used in addTree.
const defaultTreeStructure: TreeStructure = {
    rootNodes: [
        {
            label: 'Orientation',
            children: []
        },
        {
            label: 'Making & executing plans',
            children: []
        },
        {
            label: 'Completion',
            children: []
        }
    ]
};

export type TreeUpdateMetaData = {
    id: TreeId;
    newData: TreeData;
};

export type TreeUpdateStructureData = {
    id: TreeId;
    newStructure: TreeStructure;
};

export type TreeRemoveCardData = {
    id: TreeId;
    cardId: CardId;
    newStructure: TreeStructure;
};

export type TreeListResponse = {
    totalTrees: number;
    list: TreeMetadata[];
};

export type PaginationOptions = {
    page: Option<number>;
    size: Option<number>;
};

export type FilterOptions = {
    ownerId: Option<number>;
    book: string[];
    createdAfter: Option<Date>;
    createdBefore: Option<Date>;
    showOwnPrivate: Option<boolean>;
};

/** Add a tree to the database. */
export function addTree(treeData: TreeData): Promise<TreeId> {
    const treeStructure: TreeStructure = defaultTreeStructure;
    const treeAddData = {
        treeData,
        treeStructure
    };

    return apiCallPostTree('add', treeAddData);
}

/** Remove a tree and all of its cards from the database. */
export function removeTree(treeId: TreeId): Promise<void> {
    return apiCallDeleteTree(`remove/${treeId}`);
}

/** Update the structure of an existing tree. */
export function updateTreeStructure(newTreeStructure: TreeUpdateStructureData): Promise<void> {
    return apiCallPostTree('update-structure', newTreeStructure);
}

/** Remove a card from the database and update the structure of the tree with a new
 * appropriate structure. */
export function removeCardFromTree(removeCardData: TreeRemoveCardData) {
    return apiCallPostTree('remove-card', removeCardData);
}

/** Request all data of a specific tree together with all its cards from the database. */
export function getTreeWithCards(treeId: TreeId): Promise<TreeWithCards> {
    return apiCallGetTree(`get-with-cards/${treeId}`);
}

