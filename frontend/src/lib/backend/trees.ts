import type { CardGetData, CardId } from './cards';
import { apiCallPost, apiCallGet } from './index';
import type { Option } from './types';
import type { UserId } from './users';

const prefix = 'trees/';

function apiCallPostTree(path: string, body: unknown) {
    return apiCallPost(prefix + path, body);
}

function apiCallGetTree(path: string) {
    return apiCallGet(prefix + path);
}

export type TreeId = number;

/** All data of the tree, together with its cards. */
export type TreeWithCards = {
    data: TreeData;
    genData: TreeGeneratedData;
    structure: TreeStructure;
    cards: Map<CardId, CardGetData>;
};

/** The general data of the tree, NOT including its structure or autogenerated data. */
export type TreeData = {
    title: string;
    description: Option<string>;
    bookName: Option<string>;
    bookEdition: Option<string>;
    bookIsbn: Option<string>;
    bookChapter: Option<string>;
    bookExercise: Option<string>;
    assignmentText: Option<string>;
    published: boolean;
};

/** The tree structure with the cards. */
export type TreeStructure = {
    rootNodes: RootNode[];
};

/** A root node of a tree. */
export type RootNode = {
    label: string;
    children: Node[];
};

/** A node (not root) in a tree. */
export type Node = {
    cardId: CardId;
    children: Node[];
};

/** The autogenerated data of the tree. */
export type TreeGeneratedData = {
    id: TreeId;
    ownerId: UserId;
    createdAt: Date;
    lastEdited: Date;
    timesVisited: number;
    lastVisited: Option<Date>;
};

/** Add a tree to the database. */
export function addTree(tree: TreeData): Promise<TreeId> {
    return apiCallPostTree('add', tree);
}

/** Request all data of a specific tree together with all its cards from the database. */
export function getTreeWithCards(treeId: TreeId): Promise<TreeWithCards> {
    return apiCallGetTree(`get-with-cards/${treeId}`);
}
