import remarkParse from 'remark-parse';
import { unified } from 'unified';
import remarkMath from 'remark-math';
import rehypeKatex from 'rehype-katex';
import remarkRehype from 'remark-rehype';
import rehypeStringify from 'rehype-stringify';
import rehypeParse from 'rehype-parse';
import rehypeRemark from 'rehype-remark';
import remarkStringify from 'remark-stringify';
import rehypeSanitize from 'rehype-sanitize';
import { rehypeMathToProsekit, rehypeRemarkDivHandler, rehypeRemarkSpanHandler } from './math';
import type { Handle } from 'hast-util-to-mdast';
import { rehypeRemarkImgHandler, remarkRehypeTextHandler } from './imageRemark';

// Note:
// If you want to debug any of these functions,
// you can put a `.use(() => console.log)` in between where you want to look.

/** The html generated is intended to be shown directly to the user. */
export function markdownToFinalHtml(markdown: string): string {
    const processor = unified()
        .use(remarkParse)
        .use(remarkMath)
        .use(remarkRehype, {
            handlers: { text: remarkRehypeTextHandler }
        })
        .use(rehypeSanitize)
        .use(rehypeKatex)
        .use(rehypeStringify);

    return processor.processSync(markdown).toString();
}

/** The html generated is intended to be given to prosekit, so that it can convert it to its interal format. */
export function markdownToProsekitHtml(markdown: string): string {
    const processor = unified()
        .use(remarkParse)
        .use(remarkMath)
        .use(remarkRehype, {
            handlers: { text: remarkRehypeTextHandler }
        })
        .use(rehypeSanitize)
        .use(rehypeMathToProsekit)
        .use(rehypeStringify);

    return processor.processSync(markdown).toString();
}

/** The html is expected to be generated by prosekit, the math format will be fixed. */
export function markdownFromProsekitHtml(html: string): string {
    const rehypeRemarkHandlers: Record<string, Handle> = {
        img: rehypeRemarkImgHandler,
        span: rehypeRemarkSpanHandler,
        div: rehypeRemarkDivHandler
    };

    const processor = unified()
        .use(rehypeParse)
        .use(rehypeRemark, {
            handlers: rehypeRemarkHandlers
        })
        .use(remarkMath)
        .use(remarkStringify);

    return processor.processSync(html).toString();
}
