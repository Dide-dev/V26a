import type { CardData, CardId } from './cards';
import {
    apiCallPost,
    apiCallGet,
    apiCallDelete,
    apiCallEmptyPost,
    apiCallPut,
    apiCallEmptyDelete
} from './index';
import type { Option } from './types';
import type { UserId } from './users';
import type { PaginationOptions } from '$lib/pagination';

const prefix = 'trees';

function apiCallPostTree(path: string, body: unknown) {
    return apiCallPost(prefix + path, body);
}

function apiCallPutTree(path: string, body: unknown) {
    return apiCallPut(prefix + path, body);
}

function apiCallGetTree(path: string) {
    return apiCallGet(prefix + path);
}

function apiCallDeleteTree(path: string) {
    return apiCallEmptyDelete(prefix + path);
}

function apiCallDeleteTreeWithBody(path: string, body: unknown) {
    return apiCallDelete(prefix + path, body);
}

function apiCallDuplicateTree(path: string) {
    return apiCallEmptyPost(prefix + path);
}

export type TreeId = number;

/** All data of the tree, together with its cards. */
export type TreeWithCards = {
    metadata: TreeMetadata;
    structure: TreeStructure;
    cards: Record<CardId, CardData>;
};

/** The general data of the tree, NOT including its structure or autogenerated data. */
export type TreeData = {
    title: string;
    languageCode: string;
    tags: string[];
    description: string;
    subjectId: Option<number>;
    bookName: string;
    bookEdition: string;
    bookAuthor: string;
    bookIsbn: Option<string>;
    bookChapter: string;
    bookExercise: string;
    assignmentText: string;
    published: boolean;
};

/** The tree structure with the cards. */
export type TreeStructure = {
    rootNodes: RootNode[];
};

/** A root node of a tree. */
export type RootNode = {
    label: string;
    children: Node[];
};

/** A node (not root) in a tree. */
export type Node = {
    cardId: CardId;
    children: Node[];
};

/** The autogenerated data of the tree. */
export type TreeGeneratedData = {
    id: TreeId;
    ownerId: UserId;
    createdAt: Date;
    lastModified: Date;
    timesVisited: number;
    lastVisited: Option<Date>;
};

export type TreeLinkedData = {
    ownerName: Option<string>;
    subjectName: Option<string>;
    coAuthors: UserId[];
};

export type TreeMetadata = {
    data: TreeData;
    genData: TreeGeneratedData;
    linkedData: TreeLinkedData;
};

export type TreeAddData = {
    treeData: TreeData;
    treeStructure: TreeStructure;
};

export type Subject = {
    id: number;
    languageCode: string;
    name: string;
};

export type Language = {
    code: string;
    name: string;
};

// Default tree structure used in addTree.
const defaultTreeStructure: TreeStructure = {
    rootNodes: [
        {
            label: 'Orientation',
            children: []
        },
        {
            label: 'Making & executing plans',
            children: []
        },
        {
            label: 'Completion',
            children: []
        }
    ]
};

export type TreeListResponse = {
    totalTrees: number;
    trees: TreeMetadata[];
};

export type FilterOptions = {
    ownerId: Option<number>;
    book: string[];
    createdAfter: Option<Date>;
    createdBefore: Option<Date>;
    showOwnPrivate: Option<boolean>;
    editable: Option<boolean>;
};

/** Add a tree to the database. */
export function addTree(treeData: TreeData): Promise<TreeId> {
    const treeStructure: TreeStructure = defaultTreeStructure;
    const treeAddData = {
        treeData,
        treeStructure
    };

    return apiCallPostTree('', treeAddData);
}

/** Remove a tree and all of its cards from the database. */
export function removeTree(treeId: TreeId): Promise<void> {
    return apiCallDeleteTree(`/${treeId}`);
}

/** Update the structure of an existing tree. */
export function updateTreeStructure(
    treeId: TreeId,
    newTreeStructure: TreeStructure
): Promise<void> {
    return apiCallPutTree(`/${treeId}/structure`, newTreeStructure);
}

/** Add a card to the database */
export function addCard(treeId: TreeId, card: CardData): Promise<CardId> {
    return apiCallPostTree(`/${treeId}/cards`, card);
}

/** Remove a card from the database and update the structure of the tree with a new
 * appropriate structure. */
export function removeCardFromTree(
    treeId: TreeId,
    cardId: CardId,
    newTreeStructure: TreeStructure
) {
    return apiCallDeleteTreeWithBody(`/${treeId}/cards/${cardId}`, newTreeStructure);
}

/** Request all data of a specific tree together with all its cards from the database. */
export function getTreeWithCards(treeId: TreeId): Promise<TreeWithCards> {
    return apiCallGetTree(`/${treeId}`);
}

/** Update the metadata of a specific tree. */
export function updateTreeMetaData(treeId: TreeId, newTreeData: TreeData): Promise<void> {
    return apiCallPutTree(`/${treeId}`, newTreeData);
}

export function isNullOrEmpty(value: unknown): boolean {
    return value == null || (Array.isArray(value) && value.length === 0);
}

export type CoAuthorizeResponse =
    | { type: 'Success' }
    | { type: 'UsernameDoesNotExist' }
    | { type: 'UserAlreadyAuthorized' };

export function getPaginationAndFilterParams(
    pageOptions: PaginationOptions,
    filterOptions: FilterOptions
): string {
    const params = new URLSearchParams();

    Object.entries(pageOptions).forEach(([key, value]) => {
        if (value !== null) {
            params.append(key, String(value));
        }
    });

    Object.entries(filterOptions).forEach(([key, value]) => {
        if (!isNullOrEmpty(value)) {
            // For array values, all items need their own query parameter.
            if (Array.isArray(value)) {
                value.forEach((item) => params.append(key, String(item)));
            } else {
                // The JSON stringify is needed to get the dates in rfc3339 format instead of ISO format
                // because there is a different implementation of toJSON and toString
                params.append(key, JSON.parse(JSON.stringify(value)));
            }
        }
    });

    return String(params);
}

/** Get the list of all trees satisfying some filters at a given page. */
export function getFilteredList(
    pageOptions: PaginationOptions,
    filterOptions: FilterOptions
): Promise<TreeListResponse> {
    const params: string = getPaginationAndFilterParams(pageOptions, filterOptions);
    return apiCallGetTree(`?${params}`);
}

/** Duplicates a tree */
export function duplicateTree(treeId: TreeId): Promise<TreeId> {
    return apiCallDuplicateTree(`/${treeId}`);
}

/** Add user as co-author to a tree. */
export function addCoAuthor(treeId: TreeId, username: string): Promise<CoAuthorizeResponse> {
    return apiCallPostTree(`/${treeId}/co-authors/${username}`, null);
}

/** Get the list of all languages. */
export function getAllLanguages(): Promise<Language[]> {
    return apiCallGetTree('/languages');
}

/** Get the list of all subjects. */
export function getAllSubjects(): Promise<Record<string, Subject[]>> {
    return apiCallGetTree('/subjects');
}

