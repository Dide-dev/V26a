use crate::{
    errors::ApiError,
    trees::{TreeData, TreeGeneratedData, TreeStructure},
};

use sqlx::{PgPool, query, query_as};

/// Add a new tree to the database, returning its assigned index.
///
/// # Arguments
/// `db` - A reference to the database connection to use for the query.
///
/// `tree_data` - The data assigned to the new tree as [`TreeData`]
///
/// `owner_id` - The id of the owner of the tree
///
/// # Returns
/// The index assigned to the new tree if successful, or an [`ApiError`] if not.
pub async fn add_tree(db: &PgPool, tree_data: TreeData, owner_id: i32) -> Result<i32, ApiError> {
    let id_record = query!(
        "INSERT INTO trees (owner_id, title, description, book_name, book_edition, book_isbn, book_chapter, book_exercise, assignment_text, structure)
        VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9, '{}')
        RETURNING id",
        owner_id,
        tree_data.title,
        tree_data.description,
        tree_data.book_name,
        tree_data.book_edition,
        tree_data.book_isbn,
        tree_data.book_chapter,
        tree_data.book_exercise,
        tree_data.assignment_text,
    )
    .fetch_one(db)
    .await
    .map_err(|_| ApiError::DatabaseException)?;

    Ok(id_record.id)
}

/// Request data of a specific tree from the database.
///
/// # Returns
/// Returns the general data of the tree, NOT including its structure or autogenerated data
pub async fn db_request_tree_data(db: &PgPool, tree_id: i32) -> Result<TreeData, ApiError> {
    let tree_data = query_as!(
        TreeData,
        "SELECT title, description, book_name, book_edition, book_isbn, book_chapter, book_exercise, assignment_text, published
        FROM trees
        WHERE id = $1",
        tree_id,
    ).fetch_one(db).await.map_err(|_| ApiError::DatabaseException)?;

    Ok(tree_data)
}

/// Request the structure of a specific tree from the database.
///
/// # Returns
/// The autogenerated data of the tree
pub async fn db_request_tree_gen_data(
    db: &PgPool,
    tree_id: i32,
) -> Result<TreeGeneratedData, ApiError> {
    let tree_structure = query_as!(
        TreeGeneratedData,
        "SELECT id, owner_id, created_at, last_edited, times_visited, last_visited
        FROM trees
        WHERE id = $1",
        tree_id,
    )
    .fetch_one(db)
    .await
    .map_err(|_| ApiError::DatabaseException)?;

    Ok(tree_structure)
}

/// Request the generated data of a specific tree from the database.
///
/// # Returns
/// The generated with the cards
pub async fn db_request_tree_structure(
    db: &PgPool,
    tree_id: i32,
) -> Result<TreeStructure, ApiError> {
    let tree_structure = query_as!(
        TreeStructure,
        "SELECT structure
        FROM trees
        WHERE id = $1",
        tree_id,
    )
    .fetch_one(db)
    .await
    .map_err(|_| ApiError::DatabaseException)?;

    Ok(tree_structure)
}
