use crate::db::trees::{add_tree, db_request_tree_data};
use crate::trees::TreeData;

use axum::http::StatusCode;
use axum::routing::{get, post};
use axum::{Extension, Json, Router};
use sqlx::PgPool;

/// Creates an `Axum` [`Router`] for the trees category.
pub fn trees() -> Router {
    Router::new()
        .route("/add-new-tree", post(add_new_tree))
        .route("/request_tree_data", get(request_tree_data))
}

/// Add a tree to the database.
/// Returns the index assigned to the new tree.
async fn add_new_tree(
    db: Extension<PgPool>,
    axum::Json(tree_data): axum::Json<TreeData>,
) -> Result<Json<i32>, StatusCode> {
    // TODO: Get owner_id from session
    let id = add_tree(&db, tree_data, -1)
        .await
        .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;

    let json_id = Json(id);
    Ok(json_id)
}

/// Request tree data from the database.
/// Returns the general data of the tree, NOT including its structure or autogenerated data.
async fn request_tree_data(
    db: Extension<PgPool>,
    axum::Json(tree_id): axum::Json<i32>,
) -> Result<Json<TreeData>, StatusCode> {
    let tree_data = db_request_tree_data(&db, tree_id)
        .await
        .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;

    Ok(Json(tree_data))
}
