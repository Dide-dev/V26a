use crate::Config;
use crate::api_v1::session::Claims;
use crate::db::trees::{add_tree, db_get_tree_data, db_get_tree_gen_data, db_get_tree_structure};
use crate::db_structs::trees::{TreeData, TreeGeneratedData, TreeStructure};

use crate::errors::ApiError;

use axum::extract::Path;
use axum::http::StatusCode;
use axum::routing::{get, post};
use axum::{Extension, Json, Router};

use sqlx::PgPool;

/// Creates an `Axum` [`Router`] for the trees category.
pub fn trees() -> Router<Config> {
    Router::new()
        .route("/add-new-tree", post(add_new_tree))
        .route("/get-tree-data/{tree_id}", get(get_tree_data))
        .route("/get-tree-structure/{tree_id}", get(get_tree_structure))
        .route("/get-tree-gen-data/{tree_id}", get(get_tree_gen_data))
}

/// Add a tree to the database.
///
/// # Returns
/// The index assigned to the new tree as [`Json`] if successful, or an [`ApiError`] if not.
async fn add_new_tree(
    claims: Claims,
    db: Extension<PgPool>,
    Json(tree_data): Json<TreeData>,
) -> Result<Json<i32>, ApiError> {
    let id = add_tree(&db, tree_data, claims.sub).await?;

    let json_id = Json(id);
    Ok(json_id)
}

/// Request data of a specific tree from the database.
///
/// # Returns
/// The general data of the tree, NOT including its structure or autogenerated data.
async fn get_tree_data(
    db: Extension<PgPool>,
    Path(tree_id): Path<String>,
) -> Result<Json<TreeData>, StatusCode> {
    let tree_id = tree_id.parse().map_err(|_| StatusCode::BAD_REQUEST)?;

    let tree_data = db_get_tree_data(&db, tree_id)
        .await
        .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;

    Ok(Json(tree_data))
}

/// Request autogenerated data of a specific tree from the database.
///
/// # Returns
/// The autogenerated data of the tree.
async fn get_tree_gen_data(
    db: Extension<PgPool>,
    Path(tree_id): Path<String>,
) -> Result<Json<TreeGeneratedData>, StatusCode> {
    let tree_id = tree_id.parse().map_err(|_| StatusCode::BAD_REQUEST)?;

    let tree_gen_data = db_get_tree_gen_data(&db, tree_id)
        .await
        .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;

    Ok(Json(tree_gen_data))
}

/// Request structure of a specific from the database.
///
/// # Returns
/// The tree structure with the card id's.
async fn get_tree_structure(
    db: Extension<PgPool>,
    Path(tree_id): Path<String>,
) -> Result<Json<TreeStructure>, StatusCode> {
    let tree_id = tree_id.parse().map_err(|_| StatusCode::BAD_REQUEST)?;

    let tree_structure = db_get_tree_structure(&db, tree_id)
        .await
        .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;

    Ok(Json(tree_structure))
}
